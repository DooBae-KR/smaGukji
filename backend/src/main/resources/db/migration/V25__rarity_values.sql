-- 등급(전설/영웅) 값을 채운다.
--
-- 장수: 전부 전설이라고 알려주셨다.
-- 전법: 스프레드시트의 «전법» 탭에 등급 열이 생겼다. 거기 있는 값을 그대로 옮긴다.
--
-- 카드 이미지에서 등급 테두리를 읽어보려던 시도는 접었다. 67장의 테두리 색을 재면
-- 64장이 같은 색으로 나오고, 가장자리를 24배로 확대해도 그냥 그림이다.
-- 등급 프레임은 게임 UI 가 카드 «바깥»에 그리는 것으로 보인다.

-- ---------------------------------------------------------------
-- 1. 장수 — 전원 전설
-- ---------------------------------------------------------------
update general set rarity = 'LEGEND';

-- ---------------------------------------------------------------
-- 2. 전법 — 등급 칸 추가
-- ---------------------------------------------------------------
alter table tactic add column rarity text;
alter table tactic add constraint ck_tactic_rarity
    check (rarity is null or rarity in ('LEGEND', 'HERO'));

comment on column tactic.rarity is 'LEGEND 전설 / HERO 영웅. 비어 있으면 아직 확인되지 않음';

-- ---------------------------------------------------------------
-- 3. «전법» 탭에서 확인된 것만 채운다
--
-- 탭에 93행이 있지만 실제로 채워진 것은 5개뿐이다. 6행부터 88행은 전부 «칠군수몰»
-- 이라는 같은 값이 반복된다(수식 채우기가 끝나지 않은 상태로 보인다).
-- 그래서 반복 구간은 읽지 않고, 사람이 실제로 입력한 5개만 옮긴다.
--
-- 등급 외에 유형·특성·발동률·설명도 같은 행에 들어 있어 함께 채운다.
-- 이 값들이 있어야 시뮬레이션이 그 전법을 «평가 대상» 으로 삼는다.
-- (지금까지는 «상세 미입력» 이라 채점에서 빠져 있었다)
--
-- 연전연승의 발동률 칸은 «100%%» 로 적혀 있다(퍼센트 기호가 두 번). 형식이 깨진
-- 값을 그럴듯하게 고쳐 넣지 않는다. 패시브라 발동 판정을 하지 않으므로 비워도
-- 분석 결과가 달라지지 않는다.
-- ---------------------------------------------------------------
with sheet(name, category, ability, rate, effect) as (values
    ('요새 함락', 'PASSIVE', 'WEAPON', 100,
     '자신의 회심 확률이 20% 증가하며, 매 턴 행동 종료 시마다 랜덤 적군 2명에게 55%→110%의 병기 피해를 준다.'),
    ('연전연승', 'PASSIVE', 'CIVIL_MARTIAL', null,
     '병기 피해를 준 후, 자신의 무력이 8→16포인트 증가하며, 최대 8회 중첩된다. 책략 피해를 준 후, 자신의 지력이 8→16포인트 증가하며, 최대 8회 중첩된다.'),
    ('적재적소', 'ACTIVE', 'DEFENSE', 75,
     '2턴 동안 지력이 가장 높은 아군 단일 목표가 받는 피해가 12.5%→25% 감소하며(지력의 영향 받음), 1스택의 방어를 획득한다.'),
    ('삼군 압도', 'PURSUIT', 'SUPPORT', 60,
     '일반 공격 후, 3턴 동안 공격 목표의 무력, 지력, 통솔이 15→30포인트 감소하며, 최대 5회 중첩될 수 있다.'),
    ('틈새 공략', 'PURSUIT', 'WEAPON', 40,
     '1턴 동안 준비 후 적군 전체에게 2턴 동안 지속되는 홍수를 부여한다. 그리고 130%→260%의 병기 피해를 주며, 32.5%→65%의 확률로 1턴 동안 지속되는 침묵 및 무장 해제 상태를 부여한다.'))
update tactic t
   set rarity       = 'LEGEND',
       category     = sheet.category,
       ability_type = sheet.ability,
       trigger_rate = sheet.rate,
       effect_text  = sheet.effect
  from sheet
 where t.name = sheet.name;
