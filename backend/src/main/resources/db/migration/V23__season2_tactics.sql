-- 시즌2 전법 16개.
--
-- 카드에 «S» 가 붙는 시즌 전법이다. 마스터 목록 시트에는 아직 없어서 동기화로는 들어오지 않는다.
-- 사람이 직접 알려준 목록이라 이름은 확실하지만, 분류·발동확률 같은 상세는 모른다.
-- 모르는 값을 그럴듯하게 채우면 분석이 «데이터가 있는 척» 하게 되므로 비워둔다.
-- 화면에서는 «상세 미입력» 으로 표시되고, 시뮬레이션 채점에서도 제외된다.
--
-- 나중에 마스터 목록 시트에 추가하면 동기화가 그대로 인식한다.
-- (지금은 시트에 없어서 «DB 에만 있는 전법» 으로 보고될 것이다. 정상이다)

alter table tactic add column season integer;
alter table tactic add constraint ck_tactic_season
    check (season is null or season >= 1);

comment on column tactic.season is '시즌 전법 번호. 카드에 S 표시가 있는 전법. 비어 있으면 기본 전법';

-- 이름이 겹치면 만들지 않고 시즌만 표시한다. 두 번 실행해도 결과가 같다.
with s2(name) as (values
    ('요새 함락'), ('연전연승'), ('적재적소'), ('삼군 압도'),
    ('틈새 공략'), ('도광양회'), ('음과 양'), ('난공불락'),
    ('병력 강화'), ('일심협력'), ('금성의 철벽'), ('허실 간파'),
    ('맹렬한 화염'), ('기민한 전술'), ('유현정책'), ('투혼의 추격'))
insert into tactic (name, season)
select s2.name, 2
  from s2
 where not exists (select 1 from tactic t where t.name = s2.name);

update tactic set season = 2
 where name in (
    '요새 함락', '연전연승', '적재적소', '삼군 압도',
    '틈새 공략', '도광양회', '음과 양', '난공불락',
    '병력 강화', '일심협력', '금성의 철벽', '허실 간파',
    '맹렬한 화염', '기민한 전술', '유현정책', '투혼의 추격');

