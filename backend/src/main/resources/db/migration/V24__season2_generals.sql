-- 시즌2 장수 13명.
--
-- 세력(위/촉/오/군/한)은 무장 상세 시트에 없다. 시트에는 진영·성향·병종·수치·고유전법만 있다.
-- 대신 카드 이미지 왼쪽 위의 세력 배지를 하나씩 확대해서 읽었다.
-- 배지 글자와 배경색(위=남색, 촉=녹색, 오=적갈색, 군=보라)이 모두 일치하는 것을 확인했다.
-- 기존 54명도 같은 방식(카드 이미지 판독)으로 넣은 값이라 출처가 같다.
--
-- 레벨은 카드 아래쪽에 «5 가후» 처럼 적힌 숫자다. 13명 모두 5 였고, 기존 54명도 전부 5.0 이다.
--
-- 나머지 값(진영·성향·병종·무력/지력/통솔/선공·고유전법)은 여기 적지 않는다.
-- 무장 시트에 이미 있고, 시트 동기화가 채운다. 두 군데에 적어두면 어느 쪽이 맞는지
-- 알 수 없게 되므로 출처를 한 곳으로 둔다.
--
-- 이름이 겹치면 만들지 않는다. 두 번 실행해도 결과가 같다.

with s2(name, faction) as (values
    ('가후',   'WEI'),
    ('사마의', 'WEI'),
    ('악진',   'WEI'),
    ('장료',   'WEI'),
    ('감부인', 'SHU'),
    ('마운록', 'SHU'),
    ('방통',   'SHU'),
    ('법정',   'SHU'),
    ('육손',   'WU'),
    ('주태',   'WU'),
    ('공손찬', 'QUN'),
    ('전풍',   'QUN'),
    ('진궁',   'QUN'))
insert into general (name, faction, level, season)
select s2.name, s2.faction, 5.0, 2
  from s2
 where not exists (select 1 from general g where g.name = s2.name);

-- 이미 있던 장수라면 시즌 표시만 맞춘다(세력은 건드리지 않는다).
update general set season = 2
 where name in ('가후', '사마의', '악진', '장료', '감부인', '마운록', '방통',
                '법정', '육손', '주태', '공손찬', '전풍', '진궁');
